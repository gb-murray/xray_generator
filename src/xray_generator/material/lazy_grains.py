"""A bounded columnar partition fixture for lazy grain identity and geometry.

This is not a realistic grain morphology prior or a scattering implementation.
Only pure, piecewise-constant phase regions are supported. Mixed/graded phase
assignment requires a later validated geometry/amount model.
"""
from __future__ import annotations

from dataclasses import dataclass
import hashlib
import math

import numpy as np

from ..model.conventions import bounds_mm as validate_bounds_mm, canonical_hash, frozen_array
from .procedural import ProceduralMaterial


@dataclass(frozen=True)
class GrainBatch:
    grain_ids: tuple[str, ...]
    phase_ids: tuple[str, ...]
    bounds_mm: np.ndarray             # [N,3,2]; exact disjoint rectangular cells
    orientations_wxyz: np.ndarray    # [N,4]; generated by stable grain identity

    def __post_init__(self):
        object.__setattr__(self, "bounds_mm", frozen_array(self.bounds_mm))
        object.__setattr__(self, "orientations_wxyz", frozen_array(self.orientations_wxyz))

    @property
    def centers_mm(self):
        return self.bounds_mm.mean(axis=2)

    @property
    def volume_mm3(self):
        return np.prod(self.bounds_mm[:, :, 1]-self.bounds_mm[:, :, 0], axis=1)


class LazyGrainGenerator:
    """Stable nonoverlapping lamellar cells, clipped at phase/sample boundaries."""

    def __init__(self, material: ProceduralMaterial, cell_width_mm: float, seed: int = 0):
        if not isinstance(material, ProceduralMaterial):
            raise TypeError("material must be ProceduralMaterial")
        if not math.isfinite(cell_width_mm) or cell_width_mm <= 0:
            raise ValueError("cell_width_mm must be finite and positive")
        if not isinstance(seed, int) or isinstance(seed, bool) or seed < 0:
            raise ValueError("seed must be a nonnegative integer")
        for region in material.recipe.regions:
            f = region.first_phase_mass_fractions
            if any(v != f[0] for v in f) or f[0] not in (0.0, 1.0):
                raise ValueError("Lazy columnar fixture requires pure constant phase regions")
        self.material, self.cell_width_mm, self.seed = material, float(cell_width_mm), seed

    @property
    def fingerprint(self):
        return canonical_hash({"generator": "bounded_columnar_partition_v1", "material": self.material.fingerprint,
                               "cell_width_mm": self.cell_width_mm, "seed": self.seed})

    def _orientation(self, grain_id):
        payload = f"{self.fingerprint}|{grain_id}|orientation".encode()
        words = np.frombuffer(hashlib.sha256(payload).digest(), dtype="<u4")
        u1, u2, u3 = np.random.Generator(np.random.Philox(words)).random(3)
        # Shoemake Haar construction, explicit wxyz convention.
        q = np.array([np.sqrt(u1)*np.cos(2*np.pi*u3),
                      np.sqrt(1-u1)*np.sin(2*np.pi*u2),
                      np.sqrt(1-u1)*np.cos(2*np.pi*u2),
                      np.sqrt(u1)*np.sin(2*np.pi*u3)])
        return -q if q[0] < 0 else q

    def iter_grains(self, bounds_mm, batch_size=1024):
        support = np.array(validate_bounds_mm(bounds_mm))
        if not isinstance(batch_size, int) or isinstance(batch_size, bool) or batch_size < 1:
            raise ValueError("batch_size must be a positive integer")
        sample = np.array(self.material.recipe.bounds_mm)
        if np.any(np.minimum(support[:, 1], sample[:, 1]) <= np.maximum(support[:, 0], sample[:, 0])):
            return
        xmin, xmax = sample[0]
        # Boundary cells, not center inclusion, determine contributors.
        lower = max(xmin, support[0, 0])
        upper = min(xmax, support[0, 1])
        first = max(0, math.floor((lower-xmin)/self.cell_width_mm))
        stop = min(math.ceil((xmax-xmin)/self.cell_width_mm), math.ceil((upper-xmin)/self.cell_width_mm))
        ids, phases, boxes, orientations = [], [], [], []
        for cell in range(first, stop):
            a, b = xmin+cell*self.cell_width_mm, min(xmax, xmin+(cell+1)*self.cell_width_mm)
            for region_index, region in enumerate(self.material.recipe.regions):
                lo, hi = max(a, region.x_nodes_mm[0]), min(b, region.x_nodes_mm[-1])
                if hi <= lo or hi <= lower or lo >= upper:
                    continue
                grain_id = f"cell-{cell}:region-{region_index}"
                box = sample.copy()
                box[0] = [lo, hi]
                phase_index = 0 if region.first_phase_mass_fractions[0] == 1 else 1
                ids.append(grain_id)
                phases.append(self.material.phase_ids[phase_index])
                boxes.append(box)
                orientations.append(self._orientation(grain_id))
                if len(ids) == batch_size:
                    yield GrainBatch(tuple(ids), tuple(phases), np.array(boxes), np.array(orientations))
                    ids, phases, boxes, orientations = [], [], [], []
        if ids:
            yield GrainBatch(tuple(ids), tuple(phases), np.array(boxes), np.array(orientations))

    def complete_reference(self, *, maximum_grains=100000):
        """Materialize a small bounded fixture only, with an explicit size guard."""
        if not isinstance(maximum_grains,int) or isinstance(maximum_grains,bool) or maximum_grains<1:
            raise ValueError("maximum_grains must be a positive integer")
        estimate = math.ceil((self.material.recipe.bounds_mm[0][1]-self.material.recipe.bounds_mm[0][0])/self.cell_width_mm)+len(self.material.recipe.regions)-1
        if estimate > maximum_grains:
            raise ValueError("Reference population exceeds maximum_grains")
        batches = list(self.iter_grains(self.material.recipe.bounds_mm, batch_size=1024))
        if not batches:
            return GrainBatch((), (), np.empty((0,3,2)), np.empty((0,4)))
        return GrainBatch(tuple(g for batch in batches for g in batch.grain_ids),
                          tuple(p for batch in batches for p in batch.phase_ids),
                          np.concatenate([b.bounds_mm for b in batches]),
                          np.concatenate([b.orientations_wxyz for b in batches]))
